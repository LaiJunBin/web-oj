export function streamJudgeWorkerLogs() {
	const encoder = new TextEncoder();
	const originalLogs = LOG_TEXT.split('\n');

	const logs: Array<string> = [];
	while (originalLogs.length > 0) {
		const takeLength = Math.min(Math.floor(Math.random() * 15) + 5, originalLogs.length);
		logs.push(JSON.stringify(originalLogs.splice(0, takeLength)));
	}

	const stream = new ReadableStream({
		start(controller) {
			const interval = setInterval(() => {
				if (logs.length === 0) {
					clearInterval(interval);
					return;
				}
				controller.enqueue(encoder.encode(createEventSourceResponse(logs.shift())));
			}, 1000);

			controller.enqueue(encoder.encode(createEventSourceResponse(logs.shift())));
		}
	});

	return new HttpResponse(stream, {
		headers: {
			'Content-Type': 'text/event-stream'
		}
	});
}
