package setup

import (
	"context"
	"fmt"
	"judge-backend/internal/config"
	"os"
	"sync"

	"github.com/testcontainers/testcontainers-go"
	"gopkg.in/yaml.v2"
)

type setup struct {
	ctx        context.Context
	config     *config.Config
	containers map[string]testcontainers.Container
}

func NewSetup(config *config.Config) *setup {
	config.Server.Port = config.Test.Server.Port
	config.Server.StoragePath = config.Test.Server.StoragePath
	// Use a test-only container label so the orphan cleanup that runs at app
	// startup never touches containers belonging to a dev server on the same
	// Docker daemon.
	config.Judge.ContainerLabel = "judge-managed-test=true"
	// Disable the periodic orphan-repair sweeps: BDD scenarios seed judgments
	// and submissions in mid-flight states (e.g. a Judging judgment no worker
	// is executing) that the 300s-default ticker would "repair" to ERROR in
	// the middle of a long suite. An explicit 0 is the documented off switch
	// (three-state knob, see JudgeConfig); the one-shot startup sweep still
	// runs — against an empty database, so it is harmless.
	zero := 0
	config.Judge.OrphanJudgmentRepairInterval = &zero
	config.Judge.OrphanSubmissionRepairInterval = &zero
	config.Judge.RejudgeCommitRepairInterval = &zero
	// Pin the default submission cooldown to 0 for the same reason the
	// intervals above are pinned: the test config is serialised from the
	// developer's own config.yaml, so whatever value it happens to carry
	// (a fresh clone copies 5 from config.example.yaml) would otherwise
	// leak into every scenario — making consecutive submits in one scenario
	// cool each other down on some machines and not others. Scenarios that
	// exercise the cooldown set an explicit per-contest-project value.
	config.Judge.SubmissionCooldownSeconds = 0
	if err := os.MkdirAll(config.Server.StoragePath, 0700); err != nil {
		panic(err)
	}
	return &setup{
		ctx:        context.Background(),
		config:     config,
		containers: make(map[string]testcontainers.Container),
	}
}

func (s *setup) writeTestConfig() error {
	file, err := os.OpenFile("config_test.yaml", os.O_RDWR|os.O_CREATE|os.O_TRUNC, 0600)
	if err != nil {
		return err
	}
	defer file.Close()

	if _, err := file.WriteString("# This file is generated by test script, do not edit\n"); err != nil {
		return err
	}

	enc := yaml.NewEncoder(file)
	if err := enc.Encode(s.config); err != nil {
		return err
	}

	return nil
}

func (s *setup) SetupInfrastructure() error {
	fmt.Println("Setting up infrastructure...")

	if err := s.setupMySQL(); err != nil {
		return err
	}

	if err := s.setupRedis(); err != nil {
		return err
	}

	if err := s.setupMongoDB(); err != nil {
		return err
	}

	if err := s.writeTestConfig(); err != nil {
		return err
	}

	go s.setupServer()

	return nil
}

func (s *setup) TerminateInfrastructure() {
	fmt.Println("Terminating infrastructure...")

	fmt.Println("Remove test storage tmp directory...")
	os.RemoveAll(s.config.Server.StoragePath)
	wg := &sync.WaitGroup{}
	for image, container := range s.containers {
		fmt.Println("Terminating container with image:", image)
		wg.Add(1)
		go func(container testcontainers.Container) {
			container.Terminate(context.Background())
			wg.Done()
		}(container)
	}

	fmt.Println("Waiting for infrastructure to terminate...")
	wg.Wait()
	fmt.Println("Infrastructure terminated.")
	s.ctx.Done()
}
