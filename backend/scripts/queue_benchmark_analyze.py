#!/usr/bin/env python3
"""Analyze queue benchmark metrics for a benchmark run using existing admin APIs.

Primary metric:
- waiting_ms = judgingStartedAt - submission.createdAt

Secondary metrics are included only as supporting observations.
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
from datetime import datetime, timezone
from pathlib import Path
from typing import Any
import urllib.error
import urllib.request
from http.cookiejar import CookieJar

DEFAULT_BASE_URL = "http://localhost:8080"
DEFAULT_API_PREFIX = "/api/v1"
DEFAULT_ADMIN_USERNAME = "admin"
DEFAULT_ADMIN_PASSWORD = "1234"
DEFAULT_CONTEST_NAME = "Queue Benchmark Contest"
DEFAULT_CONTEST_PROJECT_NAME = "Queue Benchmark Short Task"
DEFAULT_TIMEOUT_SEC = 60.0
DEFAULT_EARLY_TOLERANCE_SEC = 5.0
DEFAULT_LATE_TOLERANCE_SEC = 300.0
DEFAULT_OUTPUT_FILENAME = "analysis.json"


class ApiError(RuntimeError):
    pass


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Analyze queue benchmark metrics with waiting time as the primary metric")
    parser.add_argument("--run-log", required=True, help="Path to attempts.jsonl generated by queue_benchmark_submit.py")
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL)
    parser.add_argument("--api-prefix", default=DEFAULT_API_PREFIX)
    parser.add_argument("--admin-username", default=DEFAULT_ADMIN_USERNAME)
    parser.add_argument("--admin-password", default=DEFAULT_ADMIN_PASSWORD)
    parser.add_argument("--contest-name", default=DEFAULT_CONTEST_NAME)
    parser.add_argument("--contest-project-name", default=DEFAULT_CONTEST_PROJECT_NAME)
    parser.add_argument("--project-id", type=int, default=None)
    parser.add_argument("--timeout-sec", type=float, default=DEFAULT_TIMEOUT_SEC)
    parser.add_argument("--early-tolerance-sec", type=float, default=DEFAULT_EARLY_TOLERANCE_SEC)
    parser.add_argument("--late-tolerance-sec", type=float, default=DEFAULT_LATE_TOLERANCE_SEC)
    parser.add_argument("--output", default=None)
    return parser


def api_url(base_url: str, api_prefix: str, path: str) -> str:
    return base_url.rstrip("/") + api_prefix + path


def json_request(opener: urllib.request.OpenerDirector, method: str, url: str, payload: dict[str, Any] | None = None, timeout_sec: float = DEFAULT_TIMEOUT_SEC, extra_headers: dict[str, str] | None = None) -> tuple[int, dict[str, Any]]:
    data = None
    headers = dict(extra_headers or {})
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    request = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with opener.open(request, timeout=timeout_sec) as response:
            status = response.status
            body = response.read().decode("utf-8")
    except urllib.error.HTTPError as exc:
        status = exc.code
        body = exc.read().decode("utf-8")
    parsed = json.loads(body) if body else {}
    return status, parsed


def fetch_csrf_token(base_url: str, api_prefix: str, opener: urllib.request.OpenerDirector, timeout_sec: float) -> str:
    status, payload = json_request(opener, "GET", api_url(base_url, api_prefix, "/csrf-token"), None, timeout_sec)
    token = payload.get("data", {}).get("token")
    if status != 200 or not payload.get("success") or not token:
        raise ApiError(f"Failed to fetch CSRF token: status={status}, payload={payload}")
    return token


def login(base_url: str, api_prefix: str, username: str, password: str, timeout_sec: float) -> urllib.request.OpenerDirector:
    cookie_jar = CookieJar()
    opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(cookie_jar))
    csrf_token = fetch_csrf_token(base_url, api_prefix, opener, timeout_sec)
    status, payload = json_request(
        opener,
        "POST",
        api_url(base_url, api_prefix, "/auth/login"),
        {"username": username, "password": password},
        timeout_sec,
        extra_headers={"csrf-token": csrf_token},
    )
    if status != 200 or not payload.get("success"):
        raise ApiError(f"Admin login failed: status={status}, payload={payload}")
    return opener


def discover_project_id(base_url: str, api_prefix: str, contest_name: str, contest_project_name: str, timeout_sec: float) -> int:
    opener = urllib.request.build_opener()
    status, contests_payload = json_request(opener, "GET", api_url(base_url, api_prefix, "/public/contests"), None, timeout_sec)
    if status != 200 or not contests_payload.get("success"):
        raise ApiError(f"Failed to list public contests: status={status}, payload={contests_payload}")

    contests = contests_payload.get("data", [])
    contest = next((item for item in contests if item.get("name") == contest_name), None)
    if contest is None:
        raise ApiError(f"Contest not found by name: {contest_name}")

    status, contest_payload = json_request(
        opener,
        "GET",
        api_url(base_url, api_prefix, f"/public/contests/{contest['id']}"),
        None,
        timeout_sec,
    )
    if status != 200 or not contest_payload.get("success"):
        raise ApiError(f"Failed to get contest detail: status={status}, payload={contest_payload}")

    projects = contest_payload.get("data", {}).get("projects", [])
    project = next((item for item in projects if item.get("name") == contest_project_name), None)
    if project is None:
        raise ApiError(f"Contest project not found by name: {contest_project_name}")
    return int(project["id"])


def load_attempts(run_log: str) -> list[dict[str, Any]]:
    attempts = []
    for line in Path(run_log).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        row = json.loads(line)
        if row.get("success"):
            attempts.append(row)
    attempts.sort(key=lambda item: (item.get("request_sent_at", 0.0), item.get("username", ""), item.get("attempt_id", "")))
    return attempts


def load_run_manifest(run_log: str) -> dict[str, Any]:
    path = Path(run_log).with_name("run.json")
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def parse_timestamp(value: str | None) -> float | None:
    if not value:
        return None
    normalized = value.replace("Z", "+00:00")
    dt = datetime.fromisoformat(normalized)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.timestamp()


def percentile(values: list[float], p: float) -> float:
    if not values:
        return 0.0
    if len(values) == 1:
        return values[0]
    rank = (len(values) - 1) * p
    lower = math.floor(rank)
    upper = math.ceil(rank)
    if lower == upper:
        return values[int(rank)]
    weight = rank - lower
    return values[lower] * (1 - weight) + values[upper] * weight


def summarize(values_ms: list[float]) -> dict[str, Any]:
    sorted_values = sorted(values_ms)
    return {
        "count": len(sorted_values),
        "avg_ms": round(statistics.mean(sorted_values), 3) if sorted_values else 0.0,
        "median_ms": round(statistics.median(sorted_values), 3) if sorted_values else 0.0,
        "p95_ms": round(percentile(sorted_values, 0.95), 3) if sorted_values else 0.0,
        "p99_ms": round(percentile(sorted_values, 0.99), 3) if sorted_values else 0.0,
        "max_ms": round(max(sorted_values), 3) if sorted_values else 0.0,
        "min_ms": round(min(sorted_values), 3) if sorted_values else 0.0,
        "stdev_ms": round(statistics.pstdev(sorted_values), 3) if len(sorted_values) > 1 else 0.0,
    }


def fetch_submissions(opener: urllib.request.OpenerDirector, base_url: str, api_prefix: str, project_id: int, timeout_sec: float) -> list[dict[str, Any]]:
    status, payload = json_request(opener, "GET", api_url(base_url, api_prefix, f"/contest-projects/{project_id}/submissions"), None, timeout_sec)
    if status != 200 or not payload.get("success"):
        raise ApiError(f"Failed to fetch submissions: status={status}, payload={payload}")
    return payload.get("data", [])


def fetch_submission_detail(opener: urllib.request.OpenerDirector, base_url: str, api_prefix: str, submission_id: str, timeout_sec: float) -> dict[str, Any]:
    status, payload = json_request(opener, "GET", api_url(base_url, api_prefix, f"/submissions/{submission_id}"), None, timeout_sec)
    if status != 200 or not payload.get("success"):
        raise ApiError(f"Failed to fetch submission detail for {submission_id}: status={status}, payload={payload}")
    return payload.get("data", {})


def match_attempts_to_submissions(attempts: list[dict[str, Any]], submissions: list[dict[str, Any]], early_tolerance_sec: float, late_tolerance_sec: float) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    attempts_by_user: dict[str, list[dict[str, Any]]] = {}
    for attempt in attempts:
        attempts_by_user.setdefault(attempt["username"], []).append(attempt)

    submissions_by_user: dict[str, list[dict[str, Any]]] = {}
    for submission in submissions:
        username = submission.get("user", {}).get("username")
        if not username:
            continue
        submissions_by_user.setdefault(username, []).append(submission)

    for rows in submissions_by_user.values():
        rows.sort(key=lambda item: item["createdAt"])

    matched: list[dict[str, Any]] = []
    unmatched_attempts: list[dict[str, Any]] = []
    for username, user_attempts in attempts_by_user.items():
        user_submissions = submissions_by_user.get(username, [])
        used = set()
        for attempt in user_attempts:
            if attempt.get("submission_id"):
                matched_submission = next((row for row in user_submissions if row.get("id") == attempt.get("submission_id")), None)
                if matched_submission is None:
                    unmatched_attempts.append(attempt)
                else:
                    matched.append({"attempt": attempt, "submission": matched_submission, "matched_by": "submission_id"})
                continue

            request_at = attempt["request_sent_at"]
            selected_index = None
            for index, submission in enumerate(user_submissions):
                if index in used:
                    continue
                submission_at = parse_timestamp(submission["createdAt"])
                if submission_at is None:
                    continue
                if submission_at < request_at - early_tolerance_sec:
                    continue
                if submission_at > request_at + late_tolerance_sec:
                    break
                selected_index = index
                break
            if selected_index is None:
                unmatched_attempts.append(attempt)
                continue
            used.add(selected_index)
            matched.append({"attempt": attempt, "submission": user_submissions[selected_index], "matched_by": "time_window"})
    return matched, unmatched_attempts


def summarize_first_waiting(records: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    first_by_user: dict[str, list[float]] = {}
    for record in sorted(records, key=lambda item: (item.get("submission_created_at") or "", item.get("username") or "")):
        waiting_ms = record.get("waiting_ms")
        if waiting_ms is None:
            continue
        username = record["username"]
        if username in first_by_user:
            continue
        first_by_user[username] = [waiting_ms]
    return {username: summarize(values) for username, values in sorted(first_by_user.items())}


def build_group_summary(records: list[dict[str, Any]], usernames: list[str]) -> dict[str, Any]:
    username_set = set(usernames)
    waiting_values = [record["waiting_ms"] for record in records if record.get("username") in username_set and record.get("waiting_ms") is not None]
    first_values: dict[str, float] = {}
    for record in sorted(records, key=lambda item: (item.get("submission_created_at") or "", item.get("username") or "")):
        username = record.get("username")
        waiting_ms = record.get("waiting_ms")
        if username not in username_set or waiting_ms is None or username in first_values:
            continue
        first_values[username] = waiting_ms
    return {
        "users": sorted(username_set),
        "waiting_summary": summarize(waiting_values),
        "first_submission_waiting_summary": summarize(list(first_values.values())),
    }


def main() -> int:
    args = build_parser().parse_args()
    attempts = load_attempts(args.run_log)
    if not attempts:
        raise SystemExit("No successful attempts found in run log")

    run_manifest = load_run_manifest(args.run_log)
    project_id = args.project_id or run_manifest.get("project_id") or discover_project_id(
        args.base_url,
        args.api_prefix,
        args.contest_name,
        args.contest_project_name,
        args.timeout_sec,
    )

    opener = login(args.base_url, args.api_prefix, args.admin_username, args.admin_password, args.timeout_sec)
    submissions = fetch_submissions(opener, args.base_url, args.api_prefix, project_id, args.timeout_sec)

    min_request = min(item["request_sent_at"] for item in attempts)
    max_request = max(item["request_sent_at"] for item in attempts)
    attempt_usernames = {item["username"] for item in attempts}
    submissions = [
        submission
        for submission in submissions
        if submission.get("user", {}).get("username") in attempt_usernames
        and parse_timestamp(submission["createdAt"]) is not None
        and parse_timestamp(submission["createdAt"]) >= min_request - args.early_tolerance_sec
        and parse_timestamp(submission["createdAt"]) <= max_request + args.late_tolerance_sec
    ]

    matched, unmatched_attempts = match_attempts_to_submissions(attempts, submissions, args.early_tolerance_sec, args.late_tolerance_sec)

    records: list[dict[str, Any]] = []
    waiting_times_ms: list[float] = []
    execution_times_ms: list[float] = []
    total_times_ms: list[float] = []
    per_user_waiting: dict[str, list[float]] = {}

    for pair in matched:
        attempt = pair["attempt"]
        submission = pair["submission"]
        detail = fetch_submission_detail(opener, args.base_url, args.api_prefix, submission["id"], args.timeout_sec)
        judgments = detail.get("judgments", [])
        judgment_started_value = None
        judgment_finished_value = None
        if judgments:
            started_values = [item.get("judgingStartedAt") for item in judgments if item.get("judgingStartedAt")]
            finished_values = [item.get("judgingFinishedAt") for item in judgments if item.get("judgingFinishedAt")]
            if started_values:
                judgment_started_value = min(started_values, key=parse_timestamp)
            if finished_values:
                judgment_finished_value = min(finished_values, key=parse_timestamp)

        submission_created_at = parse_timestamp(submission["createdAt"])
        judgment_started_at = parse_timestamp(judgment_started_value)
        judgment_finished_at = parse_timestamp(judgment_finished_value)

        waiting_ms = None
        execution_ms = None
        total_ms = None
        if judgment_started_at is not None and submission_created_at is not None:
            waiting_ms = round((judgment_started_at - submission_created_at) * 1000, 3)
            waiting_times_ms.append(waiting_ms)
            per_user_waiting.setdefault(attempt["username"], []).append(waiting_ms)
        if judgment_finished_at is not None and judgment_started_at is not None:
            execution_ms = round((judgment_finished_at - judgment_started_at) * 1000, 3)
            execution_times_ms.append(execution_ms)
        if judgment_finished_at is not None and submission_created_at is not None:
            total_ms = round((judgment_finished_at - submission_created_at) * 1000, 3)
            total_times_ms.append(total_ms)

        records.append({
            "attempt_id": attempt["attempt_id"],
            "kind": attempt.get("kind", "submission"),
            "username": attempt["username"],
            "sequence_for_user": attempt.get("sequence_for_user"),
            "matched_by": pair.get("matched_by"),
            "request_sent_at": attempt["request_sent_at"],
            "submission_id": submission["id"],
            "submission_created_at": submission["createdAt"],
            "judging_started_at": judgment_started_value,
            "judging_finished_at": judgment_finished_value,
            "judgment_count": len(judgments),
            "waiting_ms": waiting_ms,
            "execution_ms": execution_ms,
            "total_ms": total_ms,
        })

    records.sort(key=lambda item: (item.get("request_sent_at") or 0.0, item.get("username") or "", item.get("attempt_id") or ""))
    for index, record in enumerate(records, start=1):
        record["request_rank"] = index

    submission_rank_source = [record for record in records if record.get("submission_created_at")]
    submission_rank_source.sort(key=lambda item: (item["submission_created_at"], item["username"], item["attempt_id"]))
    for index, record in enumerate(submission_rank_source, start=1):
        record["submission_rank"] = index

    judging_rank_source = [record for record in records if record.get("judging_started_at")]
    judging_rank_source.sort(key=lambda item: (item["judging_started_at"], item["username"], item["attempt_id"]))
    for index, record in enumerate(judging_rank_source, start=1):
        record["judging_start_rank"] = index

    per_user_waiting_summary = {username: summarize(values) for username, values in sorted(per_user_waiting.items())}
    heavy_users = run_manifest.get("heavy_users") or sorted([username for username, count in (run_manifest.get("per_user_attempt_count") or {}).items() if count > 1])
    light_users = run_manifest.get("light_users") or sorted([username for username, count in (run_manifest.get("per_user_attempt_count") or {}).items() if count == 1])
    submission_id_matched_count = sum(1 for row in records if row.get("matched_by") == "submission_id")

    output = {
        "project_id": project_id,
        "experiment_type": run_manifest.get("experiment_type", "submission_benchmark"),
        "attempt_count": len(attempts),
        "matched_count": len(matched),
        "unmatched_attempt_count": len(unmatched_attempts),
        "submission_id_matched_count": submission_id_matched_count,
        "primary_metric": "waiting_ms",
        "summary_metric_description": "queue waiting time from submission.createdAt to judgingStartedAt",
        "summary": summarize(waiting_times_ms),
        "execution_summary": summarize(execution_times_ms),
        "total_summary": summarize(total_times_ms),
        "per_user_waiting": per_user_waiting_summary,
        "first_submission_per_user_waiting": summarize_first_waiting(records),
        "heavy_user_group": build_group_summary(records, heavy_users),
        "light_user_group": build_group_summary(records, light_users),
        "run_manifest": run_manifest,
        "unmatched_attempts": unmatched_attempts,
        "records": records,
    }

    output_path = Path(args.output) if args.output else Path(args.run_log).with_name(DEFAULT_OUTPUT_FILENAME)
    output_path.write_text(json.dumps(output, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({
        "output": str(output_path),
        "primary_metric": output["primary_metric"],
        "summary_metric_description": output["summary_metric_description"],
        "summary": output["summary"],
        "submission_id_matched_count": submission_id_matched_count,
        "heavy_user_group": output["heavy_user_group"]["waiting_summary"],
        "light_user_group": output["light_user_group"]["waiting_summary"],
        "matched_count": len(matched),
        "unmatched_attempt_count": len(unmatched_attempts),
    }, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
